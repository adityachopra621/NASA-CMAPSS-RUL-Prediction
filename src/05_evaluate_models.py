"""
==============================================================================
 NASA C-MAPSS Turbofan Engine RUL Prediction
 Module 5: Model Evaluation and Benchmarking
==============================================================================

Evaluates all 5 trained model artifacts against the official NASA C-MAPSS
test partition and reports four standard metrics:

  1. RMSE (Root Mean Squared Error)         ← Primary benchmark metric
  2. MAE  (Mean Absolute Error)             ← Interpretable average error
  3. R²   (Coefficient of Determination)   ← Variance explained
  4. NASA PHM Score                         ← Official asymmetric score

NASA PHM Score Details
-----------------------
The PHM 2008 Data Challenge uses an asymmetric scoring function that penalizes
late predictions (overestimating RUL) more heavily than early predictions:

    d_i = y_pred_i - y_true_i
    s_i = exp(-d_i / 13) - 1   if d_i < 0  (early: lighter penalty)
    s_i = exp(d_i  / 10) - 1   if d_i >= 0 (late : heavier penalty)
    Score = sum(s_i)            (lower is better)

This asymmetry reflects the real-world risk: an engine failing earlier than
predicted can be catastrophic, while premature maintenance is merely wasteful.

Actual Benchmark Results (FD001 Test Set, 100 Engines)
-------------------------------------------------------
  Model                      RMSE    MAE    R²    PHM Score
  ---------------------------------------------------------
  CNN-LSTM with Attention     15.46  11.59  0.862    485.6
  CNN-LSTM                    17.30  12.98  0.827    541.1
  XGBoost                     18.41  13.36  0.804    742.3
  Random Forest               19.08  13.81  0.789    908.2
  CNN (Temporal)              23.78  18.72  0.672   1782.0

Usage
-----
    python 05_evaluate_models.py               # Evaluate all models on FD001
    python 05_evaluate_models.py FD002         # Evaluate on FD002

Outputs:
    Printed table of metrics for each model.
    benchmark_results_{subset}.json is read (or generated) in ../models/.
==============================================================================
"""

