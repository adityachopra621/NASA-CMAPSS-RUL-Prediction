import sys
import json

import numpy as np
import joblib

os.environ["TF_CPP_MIN_LOG_LEVEL"] = "2"
os.environ["TF_ENABLE_ONEDNN_OPTS"] = "0"

from tensorflow import keras
from sklearn.metrics import mean_squared_error, mean_absolute_error, r2_score

