_src_dir = _os.path.dirname(_os.path.abspath(__file__))
_prep    = _load_module(_os.path.join(_src_dir, "01_data_preprocessing.py"), "data_preprocessing")

load_cmapss_raw           = _prep.load_cmapss_raw
transform_data            = _prep.transform_data
generate_test_last_windows= _prep.generate_test_last_windows
engineer_tabular_features = _prep.engineer_tabular_features
nasa_phm_score            = _prep.nasa_phm_score
FEATURE_COLS              = _prep.FEATURE_COLS
WINDOW_SIZE               = _prep.WINDOW_SIZE


def evaluate_all_models(
    data_dir: str = "data",
    models_dir: str = "models",
    subset: str = "FD001",
) -> dict:
    """
    Load all trained model artifacts and evaluate them on the official NASA test set.

    For deep learning models (CNN, CNN-LSTM, Attention):
      - Input: X_test of shape (N_engines, 50, 24)
      - Generated by generate_test_last_windows()

    For classical models (XGBoost, Random Forest):
      - Input: X_test_tab of shape (N_engines, 120)
      - Generated by engineer_tabular_features(is_train=False)

    For both:
      - Ground-truth: RUL_{subset}.txt (one RUL value per test engine)
      - Predictions clipped to [0, 150] (physical bounds)

    Parameters
    ----------
    data_dir : str
        Path to directory containing CMAPSS data files.
    models_dir : str
        Path to directory containing trained model artifacts.
    subset : str
        One of "FD001", "FD002", "FD003", "FD004".

    Returns
    -------
    dict
        Dictionary mapping model name → dict of metrics (rmse, mae, r2, phm_score).
    """
    print(f"\n{'='*65}")
    print(f" Model Evaluation — NASA C-MAPSS {subset} (Official Test Set)")
    print(f"{'='*65}")

    # ------------------------------------------------------------------
    # Load and prepare test data
    # ------------------------------------------------------------------
    print("\n[1/3] Preparing test data...")

    test_raw  = load_cmapss_raw(data_dir, subset, "test")
    rul_raw   = load_cmapss_raw(data_dir, subset, "RUL")
    y_test    = rul_raw["rul"].values

    scaler_path = os.path.join(models_dir, f"scaler_{subset}.joblib")
    if not os.path.exists(scaler_path):
        raise FileNotFoundError(
            f"Scaler not found: {scaler_path}\n"
            f"Run 04_train_classical_models.py first to generate the scaler."
        )
    scaler = joblib.load(scaler_path)

    test_scaled = transform_data(test_raw, scaler)

    # Sequence input for deep learning models
    X_test_seq, _ = generate_test_last_windows(test_scaled)

    # Tabular input for classical ML models
    X_test_tab, _ = engineer_tabular_features(test_scaled, is_train=False)

    print(f"       Test engines       : {len(y_test)}")
    print(f"       X_test_seq shape   : {X_test_seq.shape}")
    print(f"       X_test_tab shape   : {X_test_tab.shape}")
    print(f"       Ground-truth RUL   : min={y_test.min():.0f}  max={y_test.max():.0f}  mean={y_test.mean():.1f}")

    # ------------------------------------------------------------------
    # Define model artifacts to evaluate
    # ------------------------------------------------------------------
    model_registry = [
        {
            "name"      : "CNN-LSTM with Self-Attention",
            "type"      : "keras",
            "path"      : os.path.join(models_dir, f"cnn_lstm_attention_{subset}.keras"),
            "input"     : "sequence",
        },
        {
            "name"      : "CNN-LSTM",
            "type"      : "keras",
            "path"      : os.path.join(models_dir, f"cnn_lstm_{subset}.keras"),
            "input"     : "sequence",
        },
        {
            "name"      : "CNN",
            "type"      : "keras",
            "path"      : os.path.join(models_dir, f"cnn_{subset}.keras"),
            "input"     : "sequence",
        },
        {
            "name"      : "XGBoost",
            "type"      : "joblib",
            "path"      : os.path.join(models_dir, f"xgboost_{subset}.joblib"),
            "input"     : "tabular",
        },
        {
            "name"      : "Random Forest",
            "type"      : "joblib",
            "path"      : os.path.join(models_dir, f"random_forest_{subset}.joblib"),
            "input"     : "tabular",
        },
    ]

    # ------------------------------------------------------------------
    # Evaluate each model
    # ------------------------------------------------------------------
    print("\n[2/3] Running inference on all 5 models...")
    all_results = {}

    for entry in model_registry:
        name       = entry["name"]
        model_path = entry["path"]

        if not os.path.exists(model_path):
            print(f"  [{name}] ⚠ Artifact not found: {model_path} — SKIPPING")
            continue

        # Load model
        if entry["type"] == "keras":
            model = keras.models.load_model(model_path)
        else:
            model = joblib.load(model_path)

        # Predict
        X_input = X_test_seq if entry["input"] == "sequence" else X_test_tab
        if entry["type"] == "keras":
            preds = model.predict(X_input, verbose=0).flatten()
        else:
            preds = model.predict(X_input)

        preds = np.clip(preds, 0, 150)   # Enforce physical upper/lower bounds

        # Compute metrics
        rmse = float(np.sqrt(mean_squared_error(y_test, preds)))
        mae  = float(mean_absolute_error(y_test, preds))
        r2   = float(r2_score(y_test, preds))
        phm  = nasa_phm_score(y_test, preds)

        all_results[name] = {
            "rmse"      : round(rmse, 2),
            "mae"       : round(mae, 2),
            "r2"        : round(r2, 4),
            "phm_score" : round(phm, 1),
        }

    # ------------------------------------------------------------------
    # Print benchmark table
    # ------------------------------------------------------------------
    print("\n[3/3] Benchmark Results\n")
    print(f"  {'Model':<35} {'RMSE':>6}  {'MAE':>6}  {'R²':>6}  {'PHM Score':>10}")
    print("  " + "-" * 65)

    sorted_results = sorted(all_results.items(), key=lambda x: x[1]["rmse"])
    for i, (model_name, m) in enumerate(sorted_results):
        marker = " ◄ BEST" if i == 0 else ""
        print(
            f"  {model_name:<35} {m['rmse']:>6.2f}  {m['mae']:>6.2f}  {m['r2']:>6.3f}  {m['phm_score']:>10.1f}{marker}"
        )
    print("  " + "-" * 65)

    print("\n  Metric explanations:")
    print("    RMSE      : Root Mean Squared Error (cycles) — lower is better")
    print("    MAE       : Mean Absolute Error (cycles) — lower is better")
    print("    R²        : Coefficient of determination — higher is better (max=1.0)")
    print("    PHM Score : NASA asymmetric score — lower is better (penalizes late predictions)")

    return all_results


def load_benchmark_json(models_dir: str, subset: str) -> dict:
    """
    Load pre-computed benchmark results from the JSON artifact.

    The benchmark_results_{subset}.json file is generated by train_models.py
    and contains metrics + per-engine predictions for all 5 models.

    Parameters
    ----------
    models_dir : str
        Directory containing benchmark JSON files.
    subset : str
        One of "FD001", "FD002", "FD003", "FD004".

    Returns
    -------
    dict
        Full benchmark dictionary including 'models' and 'evaluations' keys.
    """
    json_path = os.path.join(models_dir, f"benchmark_results_{subset}.json")
    if not os.path.exists(json_path):
        raise FileNotFoundError(f"Benchmark results not found: {json_path}")

    with open(json_path, "r") as f:
        return json.load(f)


if __name__ == "__main__":
    subset = sys.argv[1] if len(sys.argv) > 1 else "FD001"

    project_root = os.path.join(os.path.dirname(__file__), "..")
    data_dir     = os.path.join(project_root, "data")
    models_dir   = os.path.join(project_root, "models")

    results = evaluate_all_models(data_dir=data_dir, models_dir=models_dir, subset=subset)
